    private void SearchbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SearchbtnActionPerformed
      String searchTicketId = SearchTxt.getText().trim();  // Search field input

    if (searchTicketId.isEmpty()) {
        JOptionPane.showMessageDialog(null, "Please enter a Ticket ID to search.");
        return;
    }

    try {
        // Use RMI to get the TicketService
        TicketService ticketService = ClientController.getTicketService();

        // Search for the ticket via RMI
        Ticket ticket = ticketService.searchById(searchTicketId);

        // Clear the table before displaying results
        DefaultTableModel model = (DefaultTableModel) TicketTable.getModel();
        model.setRowCount(0);

        if (ticket != null) {
            model.addRow(new Object[] {
                ticket.getTicketId(),
                ticket.getOrigin(),
                ticket.getDestination(),
                ticket.getDate(),
                ticket.getPrice(),
                ticket.getCategory(),
                ticket.getSeat()
            });
        } else {
            JOptionPane.showMessageDialog(null, "Ticket with ID " + searchTicketId + " not found.");
            loadTicketsToTable(); // Load all if not found
        }

    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(null, "Error searching ticket: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_SearchbtnActionPerformed

