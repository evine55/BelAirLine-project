    private void makeadminActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_makeadminActionPerformed
              int selectedRow = userTable.getSelectedRow();

    if (selectedRow != -1) {
        String username = userTable.getValueAt(selectedRow, 0).toString();

        try {
            // Use remote AdminService and UserService
            if (ClientController.getAdminService().isAlreadyAdmin(username)) {
                JOptionPane.showMessageDialog(this, "User '" + username + "' is already an admin.");
            } else {
                // Add admin record remotely
                Admin admin = new Admin();
                admin.setUsername(username);
                ClientController.getAdminService().createAdmin(admin);

                JOptionPane.showMessageDialog(this, "User '" + username + "' added to admins table.");
            }

            boolean updated = ClientController.getUserService().updateRoleToAdmin(username);

            if (updated) {
                JOptionPane.showMessageDialog(this, "User '" + username + "' role updated to admin.");
            } else {
                JOptionPane.showMessageDialog(this, "Failed to update role.");
            }

            loadUsersTable(); // Refresh user table after changes

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error occurred while making user admin: " + e.getMessage());
        }
    } else {
        JOptionPane.showMessageDialog(this, "Please select a user from the table.");
    }
    }//GEN-LAST:event_makeadminActionPerformed

    private void removeadminActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removeadminActionPerformed
            int selectedRow = userTable.getSelectedRow();

    if (selectedRow != -1) {
        String username = userTable.getValueAt(selectedRow, 0).toString();

        try {
            // Create admin object to delete
            Admin admin = new Admin();
            admin.setUsername(username);

            // Call remote delete method (returns Admin object or null)
            Admin deletedAdmin = ClientController.getAdminService().deleteAdmin(admin);

            if (deletedAdmin != null) {
                // If deleted, try to revert the user role
                boolean roleUpdated = ClientController.getUserService().updateRoleToUser(username);

                if (roleUpdated) {
                    JOptionPane.showMessageDialog(this, "User '" + username + "' removed from admins and role reverted to user.");
                } else {
                    JOptionPane.showMessageDialog(this, "User removed from admins but failed to revert role.");
                }

                loadUsersTable(); // Refresh user table
            } else {
                JOptionPane.showMessageDialog(this, "Failed to remove '" + username + "' from admins.");
            }
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error occurred while removing admin: " + e.getMessage());
        }
    } else {
        JOptionPane.showMessageDialog(this, "Please select a user.");
    }
    }//GEN-LAST:event_removeadminActionPerformed

