private void loadTicketsToTable() throws RemoteException {
    // Call remote method via RMI to get all tickets
    List<Ticket> tickets = ClientController.getTicketService().readAllTickets();
    // Assuming your JTable is named TicketTable
    DefaultTableModel model = (DefaultTableModel) TicketTable.getModel();
    model.setRowCount(0); // Clear existing rows
    // Populate table with ticket data
    for (Ticket ticket : tickets) {
        model.addRow(new Object[]{
            ticket.getTicketId(),
            ticket.getOrigin(),
            ticket.getDestination(),
            ticket.getDate(),
            ticket.getPrice(),
            ticket.getCategory(),
            ticket.getSeat()
        });
    }
}
  


