  private void displaySelectedTicketDetails(String username, String ticketId) {
    try {
        // Fetch booked tickets remotely by username
        List<BookedTicket> bookedTickets = ClientController.getBookedTicketService().getBookedTicketsByUsername(username);

        if (bookedTickets.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No booked tickets found for printing.");
            return;
        }

        // Find the ticket with the given ticketId
        BookedTicket bookedTicket = null;
        for (BookedTicket ticket : bookedTickets) {
            if (ticket.getTicketId().equals(ticketId)) {
                bookedTicket = ticket;
                break;
            }
        }

        if (bookedTicket != null) {
            // Create the ticket details in the requested format
            String ticketDetails =
                "=================================\n" +
                "          BELAIRLINES\n" +
                "        TICKET RECEIPT\n" +
                "=================================\n\n" +
                "Ticket ID: " + bookedTicket.getTicketId() + "\n\n" +
                "Passenger: " + bookedTicket.getUsername() + "\n\n" +
                "Phone Number: " + bookedTicket.getPhoneNumber() + "\n\n" +
                "Address: " + bookedTicket.getAddress() + "\n\n" +
                "Origin: " + bookedTicket.getOrigin() + "\n\n" +
                "Destination: " + bookedTicket.getDestination() + "\n\n" +
                "Date: " + bookedTicket.getDate() + "\n\n" +
                "Price: $" + String.format("%.2f", bookedTicket.getPrice()) + "\n\n" +
                "Category: " + bookedTicket.getCategory() + "\n\n" +
                "Seat:  " + bookedTicket.getSeat() + "\n\n" +
                "---------------------------------\n" +
                "Thank you for choosing BelairLines!\n" +
                "Contact: +250791822315\n" +
                "www.belairlines.com\n" +
                "=================================\n";

            // Display the ticket details in JTextArea
            jTextAreaReceipt.setText(ticketDetails);
        } else {
            jTextAreaReceipt.setText("Ticket not found.");
        }

    } catch (RemoteException e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error retrieving ticket details: " + e.getMessage());
    }
}


   

    



