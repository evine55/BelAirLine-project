private void loadBookedTicketsToTable() {
    try {
        // Fetch booked tickets from remote RMI service
        List<BookedTicket> bookedTickets = ClientController.getBookedTicketService().getAllBookedTickets();

        // Define column names
        String[] columnNames = { "Ticket ID", "Username", "Phone Number", "Address", "Origin", "Destination" };

        // Prepare row data
        Object[][] rowData = new Object[bookedTickets.size()][columnNames.length];

        for (int i = 0; i < bookedTickets.size(); i++) {
            BookedTicket bookedTicket = bookedTickets.get(i);
            rowData[i][0] = bookedTicket.getTicketId();
            rowData[i][1] = bookedTicket.getUsername();
            rowData[i][2] = bookedTicket.getPhoneNumber();
            rowData[i][3] = bookedTicket.getAddress();
            rowData[i][4] = bookedTicket.getOrigin();
            rowData[i][5] = bookedTicket.getDestination();
        }

        // Create and set table model
        DefaultTableModel model = new DefaultTableModel(rowData, columnNames) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // Make table non-editable
            }
        };

        // Set table model to your JTable
        if (BookedTable != null) {
            BookedTable.setModel(model);
        } else {
            JOptionPane.showMessageDialog(this, "Error: BookedTable is not initialized.");
        }

    } catch (RemoteException e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Failed to load booked tickets: " + e.getMessage());
    }
}



    

