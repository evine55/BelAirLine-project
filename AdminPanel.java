    private void TicketTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TicketTableMouseClicked
            int selectedRow = TicketTable.getSelectedRow();

    if (selectedRow == -1) return;

    try {
        // Get the ticket ID from the selected row
        String ticketId = TicketTable.getValueAt(selectedRow, 0).toString().trim();

        // Use RMI service to fetch ticket by ID
        TicketService ticketService = ClientController.getTicketService();
        Ticket ticketToUpdate = ticketService.searchById(ticketId); // Remote call

        if (ticketToUpdate != null) {
            // Populate form fields
            orginTxt.setText(ticketToUpdate.getOrigin());
            destinationTxt.setText(ticketToUpdate.getDestination());
            DateTxt.setText(ticketToUpdate.getDate() != null ? ticketToUpdate.getDate().toString() : "");
            priceTxt.setText(String.valueOf(ticketToUpdate.getPrice()));
            Category.setSelectedItem(ticketToUpdate.getCategory());
            seatTxt.setText(ticketToUpdate.getSeat());
        } else {
            JOptionPane.showMessageDialog(null, "Ticket not found!", "Info", JOptionPane.INFORMATION_MESSAGE);
        }
    } catch (Exception ex) {
        ex.printStackTrace();
        JOptionPane.showMessageDialog(null, "Error retrieving ticket: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_TicketTableMouseClicked

    private void addbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addbtnActionPerformed
     // Get and trim the input values
    String origin = orginTxt.getText().trim();
    String destination = destinationTxt.getText().trim();
    Date date = null; try { date = new java.text.SimpleDateFormat("yyyy-MM-dd").parse(DateTxt.getText()); } catch(Exception ex) { javax.swing.JOptionPane.showMessageDialog(this,"Invalid date. Use yyyy-MM-dd"); return; }
    String seat = seatTxt.getText().trim();
    String priceStr = priceTxt.getText().trim();
    String selectedCategory = (String) Category.getSelectedItem();  // if categoryTxt is a JTextField

    // Validate origin
    if (origin.isEmpty() || origin.length() < 3) {
        JOptionPane.showMessageDialog(null, "Origin must be at least 3 characters.");
        return;
    }

    // Validate destination
    if (destination.isEmpty() || destination.length() < 3) {
        JOptionPane.showMessageDialog(null, "Destination must be at least 3 characters.");
        return;
    }

    // Validate date is not in the past
    if (date == null) {
        JOptionPane.showMessageDialog(null, "Please select a valid date.");
        return;
    } else {
        Date today = new Date();
        if (date.before(today)) {
            JOptionPane.showMessageDialog(null, "Date cannot be in the past.");
            return;
        }
    }

    // Validate seat format
    if (!seat.matches("^[A-Z]{1}[0-9]{1,3}$")) {
        JOptionPane.showMessageDialog(null, "Seat format must be one letter followed by 1 to 3 digits (e.g., A1, B12).");
        return;
    }

    // Validate price
    BigDecimal price;
    try {
        price = new BigDecimal(priceStr);
        if (price.compareTo(BigDecimal.ZERO) < 0) {
            JOptionPane.showMessageDialog(null, "Price cannot be negative.");
            return;
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(null, "Invalid input! Please enter a valid number for the price.");
        return;
    }

    // Validate category as string
    if (!(selectedCategory.equalsIgnoreCase("Economy") 
          || selectedCategory.equalsIgnoreCase("Business") 
          || selectedCategory.equalsIgnoreCase("First"))) {
        JOptionPane.showMessageDialog(null, "Category must be Economy, Business, or First.");
        return;
    }

    // Create Ticket object
    Ticket ticket = new Ticket();
    ticket.setOrigin(origin);
    ticket.setDestination(destination);
    ticket.setDate(new java.sql.Date(date.getTime())); // Convert to SQL Date
    ticket.setPrice(price);
    ticket.setCategory(selectedCategory);  // assign string category directly
    ticket.setSeat(seat);

    // Use RMI to call the server's TicketService
    try {
        boolean result = ClientController.ticketService.addTicket(ticket);
        if (result) {
            JOptionPane.showMessageDialog(null, "Ticket added successfully!");
            clear();
            loadTicketsToTable();
        } else {
            JOptionPane.showMessageDialog(null, "Failed to add ticket. Please try again.");
        }
    } catch (Exception ex) {
        ex.printStackTrace();
        JOptionPane.showMessageDialog(null, "Server error: " + ex.getMessage());
    }
       
    }//GEN-LAST:event_addbtnActionPerformed

